// Writes src/og/backdrop-data.ts: the flowy backdrop inlined as base64. Satori has to embed the image as a data
// URI, and a bundled server route can't reliably find a file next to itself, so the bytes travel in a module that
// backdrop.ts only imports when a card asks for them. Run after changing src/og/assets/backdrop.jpg.
import { readFileSync, writeFileSync } from 'node:fs'

const base64 = readFileSync(new URL('../src/og/assets/backdrop.jpg', import.meta.url)).toString('base64')
writeFileSync(
    new URL('../src/og/backdrop-data.ts', import.meta.url),
    `// Generated by scripts/gen-og-backdrop.mjs from src/og/assets/backdrop.jpg. Don't edit.\nexport const BACKDROP_JPEG_BASE64 =\n    '${base64}'\n`,
)

// Writes src/index.ts: Kevin's additions plus every shadcn component in src/components/ui, so components added
// by `shadcn add` (or the weekly sync) are importable by name without editing anything, plus the AI Elements in
// src/components/ai. Runs on every build.
//
// The root never changes what an existing name means. Where a newer file exports a name the root already has, the
// root keeps the existing one and the newer one stays importable from its own subpath:
// - ui/sonner's Toaster and toast (the root's are ui/toast's); the root has them as SonnerToaster and sonnerToast.
// - any AI Element whose name is taken (e.g. Message, MessageContent from ui/message): only from
//   '@kevinschaich/components/ai/<name>'. The build prints each one it leaves out.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs'

const src = new URL('../src/', import.meta.url)
const read = (path) => readFileSync(new URL(path, src), 'utf8')
const list = (dir) =>
    readdirSync(new URL(dir, src))
        .filter((f) => f.endsWith('.tsx'))
        .map((f) => f.slice(0, -4))
        .sort()

// The names a module exports, each with whether it is type-only: `export { a, type B, c as d }` blocks and
// `export function|const|class|type|interface X` declarations.
function exportsOf(code) {
    const names = new Map()
    for (const [, typeBlock, body] of code.matchAll(/export\s+(type\s+)?\{([^}]*)\}/g)) {
        for (const raw of body.split(',')) {
            const item = raw.replace(/\/\/.*$/gm, '').trim()
            if (!item) continue
            const type = Boolean(typeBlock) || /^type\s/.test(item)
            const name = item.replace(/^type\s+/, '').split(/\s+as\s+/).at(-1).trim()
            names.set(name, type)
        }
    }
    for (const [, kind, name] of code.matchAll(/export\s+(?:declare\s+)?(function|const|let|class|type|interface|enum)\s+([A-Za-z_$][\w$]*)/g)) {
        names.set(name, kind === 'type' || kind === 'interface')
    }
    return names
}

const SUBPATH_ONLY = { sonner: ['Toaster', 'toast'] }

const additions = [
    "export * from './byline'",
    "export { Byline } from './byline-react'",
    "export { DataSources, type DataSource } from './data-sources'",
    "export { Stat } from './stat'",
    "export { Leaderboard, type LeaderboardColumn } from './leaderboard'",
    "export { TradeoffChart, type TradeoffPoint } from './tradeoff-chart'",
    "export { initAnalytics, POSTHOG_KEY, POSTHOG_HOST, POSTHOG_OPTIONS } from './analytics'",
    "export { MapControls, ControlButton, type MapControlsProps, type MapLike } from './map-controls'",
]

const taken = new Set()
for (const line of additions) {
    const braces = line.match(/\{([^}]*)\}/)
    if (braces) {
        for (const item of braces[1].split(',')) taken.add(item.replace(/^\s*type\s+/, '').trim())
    } else {
        const from = line.match(/from '\.\/(.+)'/)[1]
        for (const name of exportsOf(read(`${from}.ts`)).keys()) taken.add(name)
    }
}

const named = (names, path) =>
    `export { ${names.map(([n, type]) => (type ? `type ${n}` : n)).join(', ')} } from '${path}'`

const uiLines = []
for (const n of list('components/ui')) {
    const names = exportsOf(read(`components/ui/${n}.tsx`))
    const skip = SUBPATH_ONLY[n]
    if (skip) {
        uiLines.push(named([...names].filter(([name]) => !skip.includes(name)), `./components/ui/${n}`))
    } else {
        uiLines.push(`export * from './components/ui/${n}'`)
    }
    for (const name of names.keys()) if (!skip?.includes(name)) taken.add(name)
}

const aiLines = []
for (const n of list('components/ai')) {
    const names = [...exportsOf(read(`components/ai/${n}.tsx`))]
    const kept = names.filter(([name]) => !taken.has(name))
    const left = names.filter(([name]) => taken.has(name)).map(([name]) => name)
    if (left.length) console.log(`gen-index: ai/${n} not at the root (name taken): ${left.join(', ')}`)
    for (const [name] of kept) taken.add(name)
    if (kept.length) aiLines.push(named(kept, `./components/ai/${n}`))
}

writeFileSync(
    new URL('index.ts', src),
    [
        '// Generated by scripts/gen-index.mjs on every build; edit that script, not this file.',
        '',
        "// Kevin's additions: the byline, Data sources dialog, Stat, Leaderboard, TradeoffChart, analytics and page helpers.",
        ...additions,
        '',
        '// Every shadcn component (base-nova style, zinc), customized where commented, plus DataTable. Also importable one',
        "// at a time from '@kevinschaich/components/ui/<name>'.",
        ...uiLines,
        '',
        "// shadcn's AI Elements, except names the root already has. Each is also '@kevinschaich/components/ai/<name>'.",
        ...aiLines,
        '',
    ].join('\n'),
)
